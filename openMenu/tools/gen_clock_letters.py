"""Draws the letters of the header clock font (bios_clock_letters.inc) in the style of the BIOS digit glyphs.
Run: python3 tools/gen_clock_letters.py  (needs Pillow; writes src/bios_engine/src/bios_clock_letters.inc).
The comparison sheet part needs out/glyphs.pgm from the ROM and is skipped when it is not there."""
import math, os
from PIL import Image, ImageDraw
SS=8; SW=2.0
def canvas(): 
    return Image.new('L',(16*SS,16*SS),0)
def P(pts): return [(x*SS,y*SS) for x,y in pts]
def stroke(d,pts,w=SW):
    pts=P(pts); d.line(pts,fill=255,width=int(w*SS),joint='curve')
    r=w*SS/2
    for x,y in pts: d.ellipse([x-r,y-r,x+r,y+r],fill=255)
def arc(cx,cy,rx,ry,a0,a1,n=40):
    return [(cx+rx*math.cos(math.radians(a0+(a1-a0)*i/n)), cy-ry*math.sin(math.radians(a0+(a1-a0)*i/n))) for i in range(n+1)]
def g_D(d): stroke(d,[(2.4,1.8),(2.4,12.6)]); stroke(d,[(2.4,1.8),(5.2,1.8)]+arc(5.2,7.2,4.2,5.4,90,-90)[1:]+[(2.4,12.6)])
def g_C(d): stroke(d,arc(6.6,7.2,4.6,5.4,40,320))
def g_N(d): stroke(d,[(2.4,12.6),(2.4,1.8),(9.2,12.6),(9.2,1.8)])
def g_o(d): stroke(d,arc(5.4,9.0,3.9,3.9,0,360,60))
def g_w(d): stroke(d,[(1.4,5.2),(3.6,12.6),(5.7,6.8),(7.8,12.6),(10.0,5.2)])
def g_e(d): stroke(d,[(1.8,9.0),(9.0,9.0)]+arc(5.4,9.0,3.6,3.9,0,320)[1:])
def g_t(d): stroke(d,[(3.8,2.6),(3.8,10.6)]+arc(6.2,10.6,2.4,2.0,180,270)[1:]+[(6.6,12.6)]); stroke(d,[(1.4,5.4),(6.8,5.4)])
def g_bang(d): stroke(d,[(3.0,1.8),(3.0,9.4)]); d.ellipse([ (3.0-1.2)*SS,(12.1-1.2)*SS,(3.0+1.2)*SS,(12.1+1.2)*SS],fill=255)
def g_A(d): stroke(d,[(1.4,12.6),(5.4,1.8),(9.4,12.6)]); stroke(d,[(2.8,9.0),(8.0,9.0)],2.0)
def g_P(d): stroke(d,[(2.4,12.6),(2.4,1.8)]); stroke(d,[(2.4,1.8),(5.6,1.8)]+arc(5.6,5.0,3.6,3.2,90,-90)[1:]+[(2.4,8.2)])
def g_M(d): stroke(d,[(2.4,12.6),(2.4,1.8),(6.0,9.4),(9.6,1.8),(9.6,12.6)])
G=[('D',g_D),('C',g_C),('N',g_N),('o',g_o),('w',g_w),('e',g_e),('t',g_t),('!',g_bang),('A',g_A),('P',g_P),('M',g_M)]
out=[]; sheet=Image.new('L',(16*len(G),16),0)
for i,(ch,fn) in enumerate(G):
    c=canvas(); d=ImageDraw.Draw(c); fn(d)
    im=c.resize((16,16),Image.LANCZOS); sheet.paste(im,(i*16,0))
    out.append((ch,[255-int(im.getpixel((x,y))*0.82) for y in range(16) for x in range(16)]))
# compare sheet with ROM digits
if os.path.exists('out/glyphs.pgm'):
    rom=Image.open('out/glyphs.pgm').convert('L')  # 255-g
    combo=Image.new('L',(16*(14+len(G)),16),0)
    for k in range(14): combo.paste(Image.eval(rom.crop((k*16,0,k*16+16,16)),lambda v:255-v),(k*16,0))
    combo.paste(sheet,(14*16,0))
    combo.resize((combo.width*5,80),Image.NEAREST).save('out/letters.png')
# C source
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','src','bios_engine','src','bios_clock_letters.inc'),'w') as f:
    f.write('/* Letters for the header clock font, drawn to match the BIOS digit glyphs (16x16, 255 = clear, 0 = solid, as the ROM\n * glyphs at 0x8C071AB0). The ROM has only the digits and / : . so these were made for the player counts and AM/PM:\n * generated by a script from stroke outlines, 2.0 px strokes, ink 82%, cap height 12. Order: ' + ' '.join(c for c,_ in G) + ' */\n')
    f.write('static const char clock_letter_chars[] = "%s";\nstatic const uint8_t clock_letter_glyphs[%d][256] = {\n' % (''.join(c for c,_ in G),len(G)))
    for ch,data in out:
        f.write('    {/* %s */' % ch)
        for i,v in enumerate(data):
            if i%16==0: f.write('\n        ')
            f.write('%d,'%v)
        f.write('\n    },\n')
    f.write('};\n')
print('ok')
