"""Draws "Now!" and "DCNET" in the style of the BIOS "Dreamcast" wordmark (thin humanist strokes, cap height 15 and baseline 23 in
the 128x32 header logo texture) and writes src/openmenu/src/logo_text.inc: 8-bit coverage masks (255 = ink), 32 rows each.
Run: python3 tools/gen_logo_text.py  (needs Pillow). The ROM has only the letters of "Dreamcast", so the others are made here."""
import math, os
from PIL import Image, ImageDraw
SS = 8
SW = 1.75            # stroke width in texture pixels (the wordmark's stems are about 1.7 px)
YB, YC, YX = 23.3, 8.3, 12.6   # baseline, cap top, x-height top
MID = (YB + YC) / 2

def arc(cx, cy, rx, ry, a0, a1, n=48):
    return [(cx + rx * math.cos(math.radians(a0 + (a1 - a0) * i / n)), cy - ry * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]

def stroke(d, pts, ox, w=SW):
    pts = [((x + ox) * SS, y * SS) for x, y in pts]
    d.line(pts, fill=255, width=int(w * SS), joint='curve')
    r = w * SS / 2
    for x, y in pts:
        d.ellipse([x - r, y - r, x + r, y + r], fill=255)

def D(d, ox):
    stroke(d, [(1.0, YC), (1.0, YB)], ox)
    stroke(d, [(1.0, YC), (5.0, YC)] + arc(5.0, MID, 7.4, (YB - YC) / 2, 90, -90)[1:] + [(1.0, YB)], ox); return 15
def C(d, ox):
    stroke(d, arc(8.4, MID, 7.5, (YB - YC) / 2, 42, 318), ox); return 15
def N(d, ox):
    stroke(d, [(1.0, YB), (1.0, YC), (11.4, YB), (11.4, YC)], ox); return 14
def E(d, ox):
    stroke(d, [(9.6, YC), (1.0, YC), (1.0, YB), (9.6, YB)], ox); stroke(d, [(1.0, MID), (8.0, MID)], ox); return 12
def T(d, ox):
    stroke(d, [(0.6, YC), (11.4, YC)], ox); stroke(d, [(6.0, YC), (6.0, YB)], ox); return 12
def o(d, ox):
    stroke(d, arc(5.4, (YX + YB) / 2, 4.9, (YB - YX) / 2, 0, 360, 64), ox); return 12
def w(d, ox):
    stroke(d, [(0.8, YX), (4.0, YB), (7.4, YX), (10.8, YB), (14.0, YX)], ox); return 15
def bang(d, ox):
    stroke(d, [(1.3, YC), (1.3, YB - 4.6)], ox); d.ellipse([(1.3 + ox - 1.05) * SS, (YB - 0.95 - 1.05) * SS, (1.3 + ox + 1.05) * SS, (YB - 0.95 + 1.05) * SS], fill=255); return 5

def render(glyphs, width, gap):
    c = Image.new('L', (width * SS, 32 * SS), 0)
    d = ImageDraw.Draw(c)
    x = 0.0
    for g in glyphs:
        x += g(d, x) + gap
    return c.resize((width, 32), Image.LANCZOS)

masks = {'logo_dcnet_mask': (render([D, C, N, E, T], 88, 2.3), 88), 'logo_now_mask': (render([N, o, w, bang], 56, 1.8), 56)}
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'openmenu', 'src', 'logo_text.inc')
with open(path, 'w') as f:
    f.write('/* generated by tools/gen_logo_text.py: coverage masks (255 = ink, 32 rows) of "DCNET" and "Now!" in the style of the BIOS logo */\n')
    for name, (im, wd) in masks.items():
        f.write('#define %s_W %d\nstatic const uint8_t %s[%d * 32] = {' % (name.upper(), wd, name, wd))
        for i, v in enumerate(im.tobytes()):
            if i % 24 == 0:
                f.write('\n    ')
            f.write('%d,' % v)
        f.write('\n};\n')
    sheet = Image.new('L', (88 + 4 + 56, 32), 255)
    for im, off in ((masks['logo_dcnet_mask'][0], 0), (masks['logo_now_mask'][0], 92)):
        sheet.paste(Image.eval(im, lambda v: 255 - v), (off, 0))
    sheet.resize((sheet.width * 6, sheet.height * 6), Image.NEAREST).save(os.path.join(os.environ.get('GEN_PREVIEW_DIR', '.'), 'logo_text_preview.png'))
print('ok')
